import random  # подключаем рандом для чисел

n = int(input("Размер массива n: "))
# создаем массив из n случайных дробных чисел от -10 до 10 (в одну строчку)
a = [round(random.uniform(-10, 10), 2) for i in range(n)]
print("Исходный массив:", a)

# 1. Максимальный элемент (встроенная функция max делает всё за нас)
print("1. Максимум:", max(a))

# 2. Сумма до последнего положительного
summa = 0
# переворачиваем массив и ищем первый положительный (он же последний в оригинале)
rev_a = a[::-1]
for i in range(n):
    if rev_a[i] > 0:
        # если нашли, суммируем оригинальный массив до этого индекса
        # длина n, нашли на позиции i (с конца), значит в оригинале индекс n-1-i
        summa = sum(a[:n - 1 - i])
        break
print("2. Сумма до последнего положительного:", round(summa, 2)) #round() — это встроенная функция в Python, которая округляет число до нужного количества знаков после запятой.

# 3. Сжатие массива
left = float(input("Введите a: "))
right = float(input("Введите b: "))

# оставляем только те элементы, чей модуль НЕ входит в [a, b] (в одну строчку)
new_a = [x for x in a if not (left <= abs(x) <= right)]

# добиваем нулями до размера n (сколько не хватает, столько и добавляем)
new_a += [0.0] * (n - len(new_a))

print("Массив после сжатия:", new_a)